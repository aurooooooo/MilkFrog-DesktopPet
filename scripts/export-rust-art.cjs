// Build-time bridge: preserve the exact existing feathered shoulder cover.
const { app, BrowserWindow, ipcMain } = require('electron');
const fs = require('node:fs');
const path = require('node:path');
const root = path.resolve(__dirname, '..');
app.disableHardwareAcceleration();
app.commandLine.appendSwitch('force-device-scale-factor', '1');
app.setPath('userData', path.join(root, '.test-runtime', 'rust-art'));
ipcMain.handle('settings:get', () => ({ muted: true }));
app.whenReady().then(async () => {
  try {
    const win = new BrowserWindow({ width: 960, height: 640, frame: false, show: false,
      webPreferences: { preload: path.join(root, 'src/preload.js'), offscreen: true, backgroundThrottling: false } });
    await win.loadFile(path.join(root, 'src/index.html'));
    const layers = await win.webContents.executeJavaScript(`(async()=>{
      await rig.ready;
      await new Promise(resolve=>{function check(){if(rig.pending||!rig.shoulderCover)return setTimeout(check,20);resolve();}check();});
      for(const name of ['eyePatch','angry','meow'])await rig.loadImage(name);
      const layers={...rig.images,cover:rig.shoulderCover};
      return Object.fromEntries(Object.entries(layers).map(([name,image])=>{
        const source=document.createElement('canvas');source.width=960;source.height=640;
        const ctx=source.getContext('2d');ctx.drawImage(image,0,0,960,640);
        const pixels=ctx.getImageData(0,0,960,640).data;
        let left=960,top=640,right=0,bottom=0;
        for(let y=0;y<640;y++)for(let x=0;x<960;x++)if(pixels[(y*960+x)*4+3]){
          left=Math.min(left,x);top=Math.min(top,y);right=Math.max(right,x+1);bottom=Math.max(bottom,y+1);
        }
        left=Math.max(0,left-2);top=Math.max(0,top-2);right=Math.min(960,right+2);bottom=Math.min(640,bottom+2);
        const crop=document.createElement('canvas');crop.width=right-left;crop.height=bottom-top;
        crop.getContext('2d').drawImage(source,left,top,crop.width,crop.height,0,0,crop.width,crop.height);
        return [name,{offset:[left*1.6,top*1.6],data:crop.toDataURL('image/png').split(',')[1]}];
      }));
    })()`);
    const names={base:'base',mouse:'mouse',mouseArm:'mouse-arm',keyboardArm:'keyboard-arm',eyePatch:'eye-patch',angry:'angry',meow:'meow',cover:'shoulder-cover'};
    let layout='// Generated by scripts/export-rust-art.cjs; offsets in the original 1536x1024 rig.\n';
    for(const [name,layer] of Object.entries(layers)){
      fs.writeFileSync(path.join(root,`rust/assets/${names[name]}.png`),Buffer.from(layer.data,'base64'));
      const constant=names[name].replaceAll('-','_').toUpperCase();
      layout+=`pub const ${constant}: [f32; 2] = [${layer.offset.map(v=>v.toFixed(1)).join(', ')}];\n`;
    }
    fs.writeFileSync(path.join(root,'rust/assets/layout.rs'),layout);
    app.quit();
  } catch (error) { console.error(error); app.exit(1); }
});
